//
// Cleaning rules for the linking workbook, confirmed directly against
// its own real content (1171 data rows): a blank Ability Name marks a
// row for an ability that's since been deleted from the game -- skip
// it entirely. A (name, belongsTo) pair repeated with the SAME level
// is a pure accidental duplicate -- keep one. The rare case where the
// SAME (name, belongsTo) pair appears with a DIFFERENT level (found:
// exactly 2, both null-vs-a-real-number) prefers the real, non-null
// level -- a blank level next to an otherwise-identical row reads as
// "accidentally left blank," not "no level requirement," given the
// row's own sibling disagrees. A blank "Belongs To" (found: exactly 1,
// "Elemental Mastery: Frost") means a general/unassigned ability with
// no auto-grant source -- kept in the catalog, just never linked.

import XLSX from "xlsx";
import { writeFileSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..");
const LINKS_XLSX = join(homedir(), "gamedev", "lyrian-ability-links.xlsx");
const SHEET_XLSX = join(homedir(), "gamedev", "Alba T Ross - Mirane CCS v10.3.1.xlsx");
// Real request, 2026-10-29: "rename abilitylinks to autogenerated if
// it includes more than links and I think it already does" -- this
// file holds ABILITY_LINKS, LYRIAN_CLASSES, AND LYRIAN_BREAKTHROUGHS
// (plus, as of this same request, breakthrough Cost), not just links.
const LINKS_OUTPUT = join(REPO_ROOT, "packages", "client", "src", "mods", "lyrianReferenceData.generated.ts");
const CATALOG_OUTPUT = join(REPO_ROOT, "packages", "server", "mods", "lyrian-chronicles", "data", "abilityCatalogSeed.json");

function sheetRows(workbookPath, sheetName) {
  const wb = XLSX.readFile(workbookPath, { cellFormula: false });
  const ws = wb.Sheets[sheetName];
  if (!ws) throw new Error(`sheet "${sheetName}" not found in ${workbookPath} (have: ${wb.SheetNames.join(", ")})`);
  return XLSX.utils.sheet_to_json(ws, { header: 1, raw: true, defval: null });
}

function asText(value) {
  if (typeof value === "string") return value.trim();
  if (typeof value === "number") return String(value);
  return "";
}

function asNumberOrUndefined(value) {
  if (typeof value === "number" && Number.isFinite(value)) return value;
  if (typeof value === "string" && value.trim() !== "" && Number.isFinite(Number(value))) return Number(value);
  return undefined;
}

// ---- 1. Ability links (cleaned) ----

function buildAbilityLinks() {
  const rows = sheetRows(LINKS_XLSX, "Abilities");
  /** @type {Map<string, { name: string; source: string; sourceName: string; level: number | undefined }>} */
  const byKey = new Map();
  let skippedBlankName = 0;
  for (let r = 1; r < rows.length; r++) {
    const name = asText(rows[r]?.[0]);
    if (name === "") {
      skippedBlankName++;
      continue;
    }
    const belongsToRaw = asText(rows[r]?.[1]);
    const level = asNumberOrUndefined(rows[r]?.[2]);
    const match = /^(Race|Sub-Race|Class|Breakthrough):\s*(.+)$/.exec(belongsToRaw);
    const source = match ? match[1] : "";
    const sourceName = match ? match[2].trim() : "";
    const key = `${name}|${source}|${sourceName}`;
    const existing = byKey.get(key);
    if (!existing) {
      byKey.set(key, { name, source, sourceName, level });
    } else if (existing.level === undefined && level !== undefined) {
      // Same (name, source) pair, this row has the real level the
      // earlier one was missing -- prefer it (see this script's own
      // header comment on the 2 known conflicts).
      existing.level = level;
    }
  }
  console.log(`ability links: ${rows.length - 1} raw rows, ${skippedBlankName} blank-name rows skipped, ${byKey.size} cleaned entries`);
  return [...byKey.values()].filter((e) => e.source !== ""); // unlinked (no source) entries have nothing for auto-populate to match against
}

function writeAbilityLinksModule(links) {
  const sourceMap = { Race: "race", "Sub-Race": "subRace", Class: "class", Breakthrough: "breakthrough" };
  const lines = links
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name) || a.sourceName.localeCompare(b.sourceName))
    .map((e) => `  { name: ${JSON.stringify(e.name)}, source: ${JSON.stringify(sourceMap[e.source])}, sourceName: ${JSON.stringify(e.sourceName)}${e.level !== undefined ? `, level: ${e.level}` : ""} },`);
  const content = `// GENERATED by scripts/generate-lyrian-ability-data.mjs from
// ~/gamedev/lyrian-ability-links.xlsx -- do not hand-edit. Re-run that
// script against an updated workbook (corrections, or the game's own
// rulebook changing) and commit the result instead.
//
// Which class/race/sub-race/breakthrough grants which ability, and at
// what class LEVEL (undefined for race/sub-race/breakthrough sources,
// which grant unconditionally the moment that source is present) --
// consumed by lyrianChronicles.ts's own auto-populate-abilities action.
// This data does NOT exist anywhere in the real character sheet or
// its own hidden rulebook tabs (confirmed directly) -- it's the
// user's own hand-built linking table, read once here.

export type AbilitySource = "race" | "subRace" | "class" | "breakthrough";

export interface AbilityLink {
  name: string;
  source: AbilitySource;
  sourceName: string;
  level?: number;
}

export const ABILITY_LINKS: readonly AbilityLink[] = [
${lines.join("\n")}
];
`;
  writeFileSync(LINKS_OUTPUT, content);
  console.log(`wrote ${LINKS_OUTPUT} (${links.length} entries)`);
}

// ---- 2. Ability catalog seed (full descriptive data) ----

function buildAbilityCatalog() {
  const rows = sheetRows(SHEET_XLSX, "All Abilities");
  const catalog = [];
  for (let r = 1; r < rows.length; r++) {
    const name = asText(rows[r]?.[0]);
    if (name === "") continue;
    catalog.push({
      name,
      keywords: asText(rows[r]?.[2]),
      range: asText(rows[r]?.[3]),
      description: asText(rows[r]?.[4]),
      requirement: asText(rows[r]?.[5]),
      cost: asText(rows[r]?.[6]),
      apCost: asText(rows[r]?.[7]),
      manaCost: asText(rows[r]?.[8]),
      rpCost: asText(rows[r]?.[9]),
      benefits: asText(rows[r]?.[10]),
    });
  }
  console.log(`ability catalog: ${rows.length - 1} raw rows -> ${catalog.length} real entries`);
  return catalog;
}

// ---- 3. Reference lists for the "+ Add Class"/"+ Add Breakthrough" dropdowns ----
//
// Real request, 2026-10-28: "the classes didn't have a method to add
// classes or breakthroughs, which should be done from a + button to
// add a line and a dropdown to select the thing." Read from the real
// sheet's own hidden "Classes"/"Breakthroughs" tabs (the game's own
// rulebook list, same tier as the ability catalog above) -- small
// enough (185 + 89 names) to bundle directly into the client file
// alongside ABILITY_LINKS.

function buildClassList() {
  const rows = sheetRows(SHEET_XLSX, "Classes");
  const classes = [];
  for (let r = 1; r < rows.length; r++) {
    const name = asText(rows[r]?.[0]);
    if (name === "") continue;
    const tierMatch = /(\d+)/.exec(asText(rows[r]?.[1]));
    classes.push({ name, tier: tierMatch ? Number(tierMatch[1]) : 1 });
  }
  console.log(`classes: ${rows.length - 1} raw rows -> ${classes.length} real entries`);
  return classes;
}

function buildBreakthroughList() {
  const rows = sheetRows(SHEET_XLSX, "Breakthroughs");
  const breakthroughs = [];
  for (let r = 1; r < rows.length; r++) {
    const name = asText(rows[r]?.[0]);
    if (name === "") continue;
    // Real request, 2026-10-29: "please move the breakthrough costs
    // to a separate file, maybe that autogenerated one" -- column B
    // ("Cost") on this SAME hidden tab is the real rulebook price,
    // confirmed directly (e.g. "Bully" -> 50, matching the formerly
    // hand-transcribed BREAKTHROUGH_COST_BY_ID table this replaces);
    // just never extracted here before.
    breakthroughs.push({ name, cost: asNumberOrUndefined(rows[r]?.[1]) ?? 0, description: asText(rows[r]?.[3]) });
  }
  console.log(`breakthroughs: ${rows.length - 1} raw rows -> ${breakthroughs.length} real entries`);
  return breakthroughs;
}

// Real request, 2026-10-28: race/sub-race become dropdowns too, baked
// server-side at import time (packages/server/mods/lyrian-chronicles/
// entry.ts) -- small enough (5 + 45 names) that this script just
// PRINTS them, same "a script helps produce it, a human pastes the
// literal array once" precedent the original BREAKTHROUGH_COST_BY_ID
// table used -- not worth a fragile auto-patch of entry.ts's own
// source for a list this size that essentially never changes.
function buildRaceLists() {
  const rows = sheetRows(SHEET_XLSX, "Races");
  const races = [];
  const subRaces = [];
  for (let r = 1; r < rows.length; r++) {
    const race = asText(rows[r]?.[0]);
    if (race !== "") races.push(race);
    const subRace = asText(rows[r]?.[1]);
    if (subRace !== "") subRaces.push(subRace);
  }
  return { races, subRaces };
}

function appendReferenceLists(classes, breakthroughs) {
  const classLines = classes
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((c) => `  { name: ${JSON.stringify(c.name)}, tier: ${c.tier} },`);
  const breakthroughLines = breakthroughs
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((b) => `  { name: ${JSON.stringify(b.name)}, cost: ${b.cost}, description: ${JSON.stringify(b.description)} },`);
  const addition = `
/**
 * Real request, 2026-10-28: "a + button to add a line and a dropdown
 * to select the thing" -- the FULL class/breakthrough lists (read off
 * the real sheet's own hidden "Classes"/"Breakthroughs" tabs), for
 * the "+ Add Class"/"+ Add Breakthrough" popups below. Tier is known
 * per-class here too, so a newly-added class can seed its own correct
 * Tier (and therefore Cost) immediately, the same way the real
 * importer already does for an IMPORTED class; a breakthrough's own
 * Cost/Description likewise, so a freshly-added one gets its real
 * rulebook price and a real info disclosure instead of a blank one.
 * (Real request, 2026-10-29: Cost used to be a SEPARATE hand-
 * transcribed table, lyrianChronicles.ts's own BREAKTHROUGH_COST_BY_ID
 * -- folded in here instead, read off the SAME hidden tab this
 * breakthrough list already comes from, so there's one source of
 * truth, not two kept in sync by hand.)
 */
export interface LyrianClass {
  name: string;
  tier: number;
}

export const LYRIAN_CLASSES: readonly LyrianClass[] = [
${classLines.join("\n")}
];

export interface LyrianBreakthrough {
  name: string;
  cost: number;
  description: string;
}

export const LYRIAN_BREAKTHROUGHS: readonly LyrianBreakthrough[] = [
${breakthroughLines.join("\n")}
];
`;
  writeFileSync(LINKS_OUTPUT, readFileSync(LINKS_OUTPUT, "utf-8") + addition);
  console.log(`appended LYRIAN_CLASSES (${classes.length}) and LYRIAN_BREAKTHROUGHS (${breakthroughs.length}) to ${LINKS_OUTPUT}`);
}

const links = buildAbilityLinks();
writeAbilityLinksModule(links);

const catalog = buildAbilityCatalog();
writeFileSync(CATALOG_OUTPUT, JSON.stringify(catalog, null, 2));
console.log(`wrote ${CATALOG_OUTPUT} (${catalog.length} entries)`);

const classes = buildClassList();
const breakthroughList = buildBreakthroughList();
appendReferenceLists(classes, breakthroughList);

const { races, subRaces } = buildRaceLists();
console.log("\n---- paste into packages/server/mods/lyrian-chronicles/entry.ts by hand (tiny, essentially never changes) ----");
console.log(`const RACES = ${JSON.stringify(races)};`);
console.log(`const SUB_RACES = ${JSON.stringify(subRaces)};`);
