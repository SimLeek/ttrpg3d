/**
 * This mod's own concrete catalog-entry shape -- `@ttrpg3d/shared`'s
 * `AbilityCatalogEntry` only guarantees `name`; every field below is
 * Lyrian Chronicles' own business (confirmed against the real sheet's
 * hidden "All Abilities" tab columns), not the platform's. Mirrors
 * packages/server/mods/lyrian-chronicles/entry.ts's own
 * `LyrianAbilityCatalogEntry` -- client and server mod halves don't
 * share a types module beyond the generic shared package, so this is
 * duplicated deliberately rather than invented.
 */
interface LyrianAbilityCatalogEntry extends AbilityCatalogEntry {
  keywords: string;
  range: string;
  description: string;
  requirement: string;
  cost: string;
  apCost: string;
  manaCost: string;
  rpCost: string;
  benefits: string;
}

type AbilityInfo = Pick<LyrianAbilityCatalogEntry, "name" | "keywords" | "range" | "description" | "requirement" | "cost" | "benefits">;

/** The sheet's own "no value" placeholder for a blank cell (confirmed in the real catalog data), treated the same as an actually-empty string. */
function isBlankAbilityField(value: string): boolean {
  const trimmed = value.trim();
  return trimmed === "" || trimmed === "-" || trimmed === "'-";
}

function abilityInfoFields(entry: AbilityInfo): { label: string; value: string }[] {
  const fields: { label: string; value: string }[] = [];
  if (!isBlankAbilityField(entry.cost)) fields.push({ label: "Cost", value: entry.cost });
  if (!isBlankAbilityField(entry.keywords)) fields.push({ label: "Keywords", value: entry.keywords });
  if (!isBlankAbilityField(entry.range)) fields.push({ label: "Range", value: entry.range });
  if (!isBlankAbilityField(entry.requirement)) fields.push({ label: "Requirement", value: entry.requirement });
  if (!isBlankAbilityField(entry.description)) fields.push({ label: "Description", value: entry.description });
  return fields;
}

/**
 * Real request, 2026-10-29 (playtest): "the table works fine in the
 * character sheet, [but] it does not work in the test chat, because
 * the test chat is too narrow... convert it to 1xn no matter how many
 * columns there were originally and just translate left to right then
 * top to bottom... into just top to bottom, only rows, no columns.
 * Honestly do that for both the chat and the character sheet itself."
 * One cell per `<tr>` (label row, then its own value row) instead of
 * a label/value PAIR per row -- a column can never overflow a narrow
 * panel if there's only ever one of them.
 */
function abilityInfoTableHtml(entry: AbilityInfo): string {
  const rows: string[] = [];
  for (const field of abilityInfoFields(entry)) {
    rows.push(`<tr><td><strong>${escapeHtml(field.label)}</strong></td></tr>`);
    rows.push(`<tr><td>${escapeHtml(field.value).replace(/\n/g, "<br>")}</td></tr>`);
  }
  if (!isBlankAbilityField(entry.benefits)) {
    rows.push(`<tr><td><strong>Benefits</strong></td></tr>`);
    for (const part of entry.benefits.split("|")) rows.push(`<tr><td>${escapeHtml(part.trim())}</td></tr>`);
  }
  return rows.length > 0 ? `<table class="ability-info-table"><tbody>${rows.join("")}</tbody></table>` : "<em>No information on file for this ability.</em>";
}

function abilityInfoPlainText(entry: AbilityInfo): string {
  const lines = abilityInfoFields(entry).map((field) => `${field.label}: ${field.value}`);
  if (!isBlankAbilityField(entry.benefits)) {
    lines.push("Benefits:");
    for (const part of entry.benefits.split("|")) lines.push(`- ${part.trim()}`);
  }
  return lines.length > 0 ? lines.join("\n") : "(no information on file for this ability)";
}

/**
 * Real clue, 2026-10-29 (playtest): "Alchemist's core crafting and
 * arcane barrier both do not show up even though they're in the edit
 * md stuff, so it may have generated bad markdown/html." Confirmed
 * directly against marked.js: a raw HTML attribute value (like the
 * old `data-chip-value="..."`) that spans a BLANK line -- which every
 * genuinely multi-paragraph description does -- gets treated by
 * CommonMark's own HTML-block rule as the block's END; everything
 * after the blank line is re-parsed as a plain paragraph and HTML-
 * escaped, corrupting the tag (truncated/garbage attribute, stray
 * `<p>`) badly enough DOMPurify drops the whole row. `&#10;` has no
 * literal newline BYTE in the markdown source -- the scanner never
 * sees a blank line -- and the browser decodes it back to a real `\n`
 * once parsed, same as any other HTML entity in an attribute.
 */
function escapeHtmlAttr(s: string): string {
  return escapeHtml(s).replace(/\n/g, "&#10;");
}

/** The HTML an added ability's own row becomes -- plain `<div>` (not a markdown list item) specifically so marked.js never has to reconcile block-level HTML against list-item indentation rules. */
function abilityRowHtml(entry: AbilityInfo): string {
  const safeName = escapeHtml(entry.name);
  const tableHtml = abilityInfoTableHtml(entry);
  const plainText = abilityInfoPlainText(entry);
  // Real request, 2026-10-29 (playtest): "abilities should have their
  // ability names at the top when posted, bold and underlined." The
  // name was only ever the chat-chip's own BUTTON text -- fine for
  // the sheet (it sits right next to its own <details> disclosure),
  // but the posted chat message's own `label -> value` text gets
  // dropped entirely once `html` is present (characters.ts/chatPanel.ts
  // both just show "sender: <html>", never the label) -- confirmed
  // the SAME convention a compound roll's own result group already
  // follows (`<strong>${actionLabel}</strong>` baked directly into
  // ITS OWN html for the exact same reason), just bold AND underlined
  // here per the user's own request. Baked into the CHAT payload
  // only, not the <details> body below (the name is already right
  // there as the button's own text, right next to it).
  const chatHtml = `<strong><u>${safeName}</u></strong><br>${tableHtml}`;
  return `\n\n<div class="ability-row"><button type="button" class="chat-chip" data-chip-label="${safeName}" data-chip-value="${escapeHtmlAttr(plainText)}" data-chip-html="${escapeHtmlAttr(chatHtml)}">${safeName}</button> <details><summary>ℹ</summary>${tableHtml}</details></div>`;
}

/** Whether `name` is already listed on the Abilities page -- checked against the page's own raw markdown (the `data-chip-label` an earlier `abilityRowHtml` call baked in), not a variable, since an added ability isn't one (see this section's own header). */
function abilityAlreadyListed(pages: readonly CharacterSheetPageDef[], name: string): boolean {
  const page = pages.find((p) => p.title === "Abilities");
  if (!page) return false;
  return page.markdown.includes(`data-chip-label="${escapeHtml(name)}"`);
}

